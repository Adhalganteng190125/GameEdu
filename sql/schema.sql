-- sesi_game       : sesi permainan yang dibuat guru (Speed Clash, Territory Grid, dll)
-- sesi_game_soal  : relasi many-to-many antara sesi_game dan soal
-- jawaban         : jawaban siswa pada suatu sesi_game
